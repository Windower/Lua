require('strings')
local files = require('files')
local dialog = require('dialog')
local settings = require('search_settings')

local windower_settings = windower.get_windower_settings()

local file = files.new('data/message_ids.lua')

local load_messages = function()
    if not file:exists() then
        return nil, nil
    end

    return loadstring(assert(file:read()))()
end

local get_versions = function(version)
    local tokens = version:split('_')
    local date = tonumber(tokens[1])
    local minor = tonumber(tokens[2])
    return date, minor
end

local outdated = function(old)
    if not old then
        return true
    end

    local old_date, old_minor = get_versions(old)
    local date, minor = get_versions(windower_settings.ffxi_version)
    return date > old_date or date == old_date and minor > old_minor
end

local old_version, old_messages = load_messages()

local messages
if outdated(old_version) then
    messages = {}
    local encoded_search = dialog.encode_string(settings.search)

    for _, zone_id in ipairs(settings.zones) do
        local dat_file = dialog.open_dat_by_zone_id(zone_id, 'english')
        if dat_file then
            local dat = dat_file:read('*a')
            dat_file:close()
            local ids = dialog.get_ids_matching_entry(dat, encoded_search)
            if ids[1] then
                messages[zone_id] = ids[1]
            end
        end
    end

    local zone_ids = {}
    for zone_id in pairs(messages) do
        zone_ids[#zone_ids + 1] = zone_id
    end
    table.sort(zone_ids)

    local zone_lines = {}
    for _, zone_id in ipairs(zone_ids) do
        zone_lines[#zone_lines + 1] = '    [' .. zone_id .. '] = ' .. messages[zone_id] .. ',\n'
    end

    local version = windower_settings.ffxi_version
    local disclaimer = '-- This file is automatically generated.\n\n'
    file:write(disclaimer .. 'return \'' .. version .. '\', {\n' .. table.concat(zone_lines) .. '}\n')
else
    messages = old_messages
end

local offsets = {
    greater_less = 1,
    failure = 2,
    success = 4,
    second_even_odd = 5,
    first_even_odd = 6,
    range = 7,
    less = 8,
    greater = 9,
    equal = 10,
    second_multiple = 11,
    first_multiple = 12,
    tool_failure = 13,
}

return {messages, offsets}
